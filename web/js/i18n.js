export const STRINGS = { en, he };

/** 'he' or 'en', from the setting ('system', 'he' or 'en') and the browser's languages. */
export function resolveLanguage(setting, languages = []) {
  if (setting === 'he' || setting === 'en') return setting;
  for (const tag of languages) {
    const lang = String(tag).toLowerCase();
    if (lang.startsWith('he') || lang.startsWith('iw')) return 'he';
    if (lang.startsWith('en')) return 'en';
  }
  return 'en';
}

export function makeT(lang) {
  const table = STRINGS[lang] ?? en;
  return (key, ...args) => {
    const text = table[key] ?? en[key] ?? key;
    return args.length ? text.replace(/\{(\d+)\}/g, (match, i) => (args[i] !== undefined ? String(args[i]) : match)) : text;
  };
}
